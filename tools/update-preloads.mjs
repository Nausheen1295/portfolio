#!/usr/bin/env node
/* ==========================================================================
   Adds <link rel="modulepreload"> for every module an entry point imports,
   so browsers fetch the whole graph in parallel instead of discovering it
   one import level at a time. Re-run after adding/removing JS modules:

     node tools/update-preloads.mjs
   ========================================================================== */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PAGES = { "index.html": "js/main.js", "project.html": "js/project-page.js" };
const START = "<!-- modulepreload:start (generated by tools/update-preloads.mjs) -->";
const END = "<!-- modulepreload:end -->";

async function graph(entry, seen = new Set()) {
  const src = await readFile(path.join(ROOT, entry), "utf8");
  for (const [, spec] of src.matchAll(/^\s*(?:import|export)\s[^"']*?from\s+["'](\.{1,2}\/[^"']+)["']/gm)) {
    const dep = path.posix.normalize(path.posix.join(path.posix.dirname(entry), spec));
    if (!seen.has(dep)) { seen.add(dep); await graph(dep, seen); }
  }
  return seen;
}

for (const [page, entry] of Object.entries(PAGES)) {
  const file = path.join(ROOT, page);
  let html = await readFile(file, "utf8");
  const deps = [...(await graph(entry))].sort();
  const block = [START, ...deps.map((d) => `  <link rel="modulepreload" href="${d}" />`), `  ${END}`].join("\n");
  if (html.includes(START)) {
    html = html.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END}`), block.trimStart());
  } else {
    const tag = `<script type="module" src="${entry}"></script>`;
    if (!html.includes(tag)) throw new Error(`${page}: entry script tag not found`);
    html = html.replace(tag, `${tag}\n  ${block}`);
  }
  await writeFile(file, html);
  console.log(`${page}: ${deps.length} module preloads`);
}
